document.addEventListener('DOMContentLoaded', () => {
    
    const extractBtn = document.getElementById('extractBtn');
    const transcriptOutput = document.getElementById('transcriptOutput');
    
    if (!extractBtn) return;

    // 1. Text Chunking for Google Translate API (To avoid limits)
    function chunkText(text, length) {
        const chunks = [];
        for (let i = 0; i < text.length; i += length) {
            chunks.push(text.substring(i, i + length));
        }
        return chunks;
    }

    // 2. Google Translate Proxy Logic
    async function translateText(text, targetLang) {
        if (targetLang === 'en' || !targetLang) return text; 
        
        // Clean timestamps [0:00] for better translation accuracy
        text = text.replace(/\[\d+:\d+\]/g, ''); 

        const chunks = chunkText(text, 4000); 
        let translatedFullText = "";

        for (const chunk of chunks) {
            try {
                const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${targetLang}&dt=t&q=${encodeURIComponent(chunk)}`;
                const res = await fetch(url);
                const data = await res.json();
                
                let translatedChunk = "";
                data[0].forEach(item => { if (item[0]) translatedChunk += item[0]; });
                translatedFullText += translatedChunk + " ";
            } catch (e) {
                console.error("Translation Error: ", e);
                return "Translation failed midway. Original text:\n\n" + text;
            }
        }
        return translatedFullText;
    }

    // 3. YouTube ID Extractor (Supports multiple link formats)
    function extractYouTubeVideoId(url) {
        const regExp = /^.*(youtu.be\/|v\/|u\/\w\/|embed\/|watch\?v=|\&v=)([^#\&\?]*).*/;
        const match = url.match(regExp);
        return (match && match[2].length === 11) ? match[2] : null;
    }

    // 4. Main Extraction and Translation Execution
    extractBtn.addEventListener('click', async () => {
        const url = document.getElementById('ytUrlInput').value.trim();
        const langSelectElem = document.getElementById('langSelect');
        const lang = langSelectElem.value;
        const langName = langSelectElem.options[langSelectElem.selectedIndex].text;
        const videoId = extractYouTubeVideoId(url);

        if (!videoId) {
            alert('Please enter a valid YouTube video URL!');
            return;
        }

        // ==========================================
        // NEW VVIP AUTH & FAST CREDIT CHECK (0ms Delay)
        // ==========================================
        const isAuth = localStorage.getItem('ToolVerse_Auth') === 'true' || localStorage.getItem('isLoggedIn') === 'true';
        if (!isAuth) {
            alert("🔒 Please login from the Dashboard to use Premium Tools.");
            window.location.href = "index.html"; 
            return;
        }

        let currentCredits = parseInt(localStorage.getItem('tv_agent_credits') || "0");
        if (currentCredits <= 0) {
            alert("🎁 You have run out of Credits!");
            transcriptOutput.innerHTML = `<span style="color: #ef4444;">Insufficient Credits. Please upgrade in Dashboard.</span>`;
            return; 
        }

        extractBtn.innerHTML = "⏳ Processing...";
        extractBtn.disabled = true;
        transcriptOutput.innerHTML = `<span style="color: #a78bfa;">Fetching transcript... This might take a few seconds.</span>`;

        try {
            // Deduct 1 Credit instantly on UI
            currentCredits -= 1; 
            localStorage.setItem('tv_agent_credits', currentCredits);

            // Fetch External Transcript API
            const apiUrl = `https://youtube-transcript.ai/transcript/${videoId}.txt`;
            const response = await fetch(apiUrl);
            
            if (!response.ok) {
                throw new Error(`YouTube restricted captions for this video or they don't exist.`);
            }
            
            let rawText = await response.text();
            
            // Clean external API watermark
            rawText = rawText.replace(/---\nGenerated by https:\/\/youtube-transcript\.ai[\s\S]*/g, '');

            if (rawText && rawText.trim().length > 0) {
                
                // Translate if language is not English
                if(lang !== 'en') {
                    transcriptOutput.innerHTML = `<span style="color: #fbbf24;">Transcript found! Translating to ${langName}...</span>`;
                    rawText = await translateText(rawText, lang);
                }

                // Display Final Result
                transcriptOutput.innerText = `[Language: ${langName}]\n\n` + rawText.trim();
                
            } else {
                throw new Error("Transcript file was empty.");
            }

        } catch (error) {
            transcriptOutput.innerHTML = `<span style="color: #ef4444;">⚠️ Error: ${error.message}</span>`;
        } finally {
            extractBtn.innerHTML = "⚡ Extract & Translate";
            extractBtn.disabled = false;
        }
    });

    // 5. Copy Button Functionality
    const copyBtn = document.getElementById('copyBtn');
    if (copyBtn) {
        copyBtn.addEventListener('click', () => {
            const text = transcriptOutput.innerText;
            if(text.includes("Paste a YouTube link") || text.includes("⚠️") || text.includes("Fetching")) return;
            
            navigator.clipboard.writeText(text).then(() => {
                const originalText = copyBtn.innerText;
                copyBtn.innerText = "✅ Copied!";
                setTimeout(() => copyBtn.innerText = originalText, 2000);
            });
        });
    }

    // 6. Download Button Functionality
    const downloadTxtBtn = document.getElementById('downloadTxtBtn');
    if (downloadTxtBtn) {
        downloadTxtBtn.addEventListener('click', () => {
            const text = transcriptOutput.innerText;
            if(text.includes("Paste a YouTube link") || text.includes("⚠️") || text.includes("Fetching")) return;
            
            const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
            const anchor = document.createElement('a');
            anchor.href = URL.createObjectURL(blob);
            anchor.download = 'ToolVerse-Transcript.txt';
            anchor.click();
        });
    }
});
